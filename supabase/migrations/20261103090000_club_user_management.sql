-- Phase 1: add Club-scoped roles and administration without changing existing policies.
insert into public.permissions (permission_key, description) values
  ('club:portal:view', 'Access to the Club Maut & Länderinfo portal'),
  ('club:admin', 'Manage Club users and Club content')
on conflict (permission_key) do update set description = excluded.description;

insert into public.app_groups (slug, name) values
  ('club-member', 'Club-Mitglied'),
  ('club-admin', 'Club-Verwaltung')
on conflict (slug) do update set name = excluded.name;

insert into public.group_permissions (group_id, permission_id)
select g.id, p.id from public.app_groups g cross join public.permissions p
where (g.slug = 'club-member' and p.permission_key = 'club:portal:view')
   or (g.slug = 'club-admin' and p.permission_key in ('club:portal:view', 'club:admin'))
on conflict do nothing;

-- Preserve the current Club access during the migration. Homepage memberships are not changed.
insert into public.group_members (user_id, group_id)
select gm.user_id, target.id
from public.group_members gm
join public.app_groups source on source.id = gm.group_id and source.slug = 'campions-club'
cross join public.app_groups target
where target.slug = 'club-member'
on conflict do nothing;

-- Existing administrators receive Club administration so nobody is locked out during cutover.
insert into public.group_members (user_id, group_id)
select gm.user_id, target.id
from public.group_members gm
join public.app_groups source on source.id = gm.group_id and source.slug = 'admin'
cross join public.app_groups target
where target.slug = 'club-admin'
on conflict do nothing;

create table if not exists public.club_membership_audit (
  id bigint generated by default as identity primary key,
  target_user_id uuid not null references auth.users(id) on delete cascade,
  changed_by uuid references auth.users(id) on delete set null,
  enabled boolean not null,
  changed_at timestamptz not null default now()
);
alter table public.club_membership_audit enable row level security;
revoke all on public.club_membership_audit from anon, authenticated;
grant select on public.club_membership_audit to authenticated;
drop policy if exists "club admins read membership audit" on public.club_membership_audit;
create policy "club admins read membership audit" on public.club_membership_audit
for select to authenticated using (public.current_user_has_permission('club:admin'));

